import React, { useRef, useState } from 'react';
import { api } from '../api/client.js';
import { Alert } from './ui.jsx';
import { IcSparkle } from './Icons.jsx';

const SUGGESTIONS = [
  'Summarize how coupons are performing',
  'Which coupon gives the best return?',
  'Is there any sign of abuse or code guessing?',
  'What should I change to improve redemptions?',
];

export default function AiAssistant({ days = 30 }) {
  const [open, setOpen] = useState(false);
  const [question, setQuestion] = useState('');
  const [answer, setAnswer] = useState(null);   // { q, text, model }
  const [err, setErr] = useState('');
  const [busy, setBusy] = useState(false);
  const box = useRef(null);

  const ask = async (q) => {
    const text = (q ?? question).trim();
    if (!text || busy) return;
    setBusy(true); setErr(''); setAnswer(null);
    try {
      const r = await api.admin.post('/api/admin/ai/ask', { question: text, days });
      setAnswer({ q: text, text: r.answer, model: r.model });
      setQuestion('');
    } catch (e) { setErr(e.message); }
    finally { setBusy(false); box.current?.focus(); }
  };

  return (
    <div className="card mb">
      <div className="card-head">
        <div className="row" style={{ gap: 8 }}>
          <IcSparkle width="18" height="18" style={{ color: 'var(--brand)' }} />
          <div><h2 style={{ fontSize: 16 }}>Ask AI</h2><div className="sub">Ask anything about your coupons, performance or abuse. Answers use aggregated numbers only, never customer details.</div></div>
        </div>
        <div className="row" style={{ gap: 8 }}>
          <button className="btn btn-sm btn-primary" disabled={busy} onClick={() => { setOpen(true); ask('Give me a short executive summary of coupon performance, anything that looks wrong, and the top 3 actions.'); }}>
            <IcSparkle />{busy ? 'Thinking…' : 'AI summary'}
          </button>
          <button className="btn btn-sm" onClick={() => setOpen(!open)}>{open ? 'Hide' : 'Ask a question'}</button>
        </div>
      </div>
      {(open || answer || err) && (
        <div className="card-body stack" style={{ gap: 12 }}>
          <div className="row row-nowrap" style={{ gap: 8 }}>
            <input ref={box} style={{ flex: 1 }} maxLength={1000} placeholder="e.g. Why is the apply success rate low?" value={question}
              onChange={(e) => setQuestion(e.target.value)} onKeyDown={(e) => e.key === 'Enter' && ask()} aria-label="Question for the AI assistant" />
            <button className="btn btn-primary" onClick={() => ask()} disabled={busy || !question.trim()}>{busy ? 'Thinking…' : 'Ask'}</button>
          </div>
          <div className="row" style={{ gap: 6, flexWrap: 'wrap' }}>
            {SUGGESTIONS.map((s) => <button key={s} className="btn btn-sm btn-ghost" disabled={busy} onClick={() => { setQuestion(s); ask(s); }}>{s}</button>)}
          </div>
          {err && <Alert kind="error">{err}</Alert>}
          {answer && (
            <div style={{ padding: '12px 14px', borderRadius: 8, background: 'var(--surface-2)', border: '1px solid var(--border)' }}>
              <div className="small muted" style={{ marginBottom: 6 }}>{answer.q}</div>
              <div style={{ whiteSpace: 'pre-wrap', fontSize: 14, lineHeight: 1.55 }}>{answer.text}</div>
              <div className="tiny muted" style={{ marginTop: 8 }}>Generated by {answer.model} · can be wrong, verify before acting</div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
